def get_w_section(name: str) -> Optional[Dict[str, float]]:
    """Look up a W-shape section by name.

    Args:
        name: Section designation, e.g. 'W12x26'.

    Returns:
        Dictionary of section properties or None if not found.
    """
    data = _W_SHAPES.get(name)
    if data is None:
        return None
    return dict(zip(_KEYS, data))


def list_w_sections() -> List[str]:
    """Return sorted list of all available W-shape section names."""
    return sorted(_W_SHAPES.keys(), key=_section_sort_key)


def search_sections(
    min_Ix: float = 0,
    max_weight: float = float('inf'),
    section_type: str = 'W',
) -> List[Dict[str, float]]:
    """Search sections by criteria.

    Args:
        min_Ix: Minimum strong-axis moment of inertia (in⁴).
        max_weight: Maximum weight per foot (lb/ft). Approximated as A * 3.4.
        section_type: Section type prefix, e.g. 'W'.

    Returns:
        List of matching section property dictionaries, sorted by weight.
    """
    results = []
    db = _W_SHAPES if section_type == 'W' else {}

    for name, data in db.items():
        props = dict(zip(_KEYS, data))
        weight_per_ft = props['A'] * 3.4  # Approximate lb/ft
        if props['Ix'] >= min_Ix and weight_per_ft <= max_weight:
            props['name'] = name
            props['weight_per_ft'] = weight_per_ft
            results.append(props)

    results.sort(key=lambda p: p['A'])
    return results


def get_section_for_design(name: str):
    """Return a SectionProperties dataclass instance for use with AISC360 design.

    Args:
        name: Section designation, e.g. 'W14x90'.

    Returns:
        SectionProperties dataclass instance, or None if not found.
    """
    props = get_w_section(name)
    if props is None:
        return None

    try:
        from ..design.AISC360 import SectionProperties
        return SectionProperties(
            name=name,
            A=props['A'], Ix=props['Ix'], Iy=props['Iy'],
            Zx=props['Zx'], Zy=props['Zy'],
            Sx=props['Sx'], Sy=props['Sy'],
            rx=props['rx'], ry=props['ry'],
            J=props['J'], Cw=props['Cw'],
            d=props['d'], tw=props['tw'],
            bf=props['bf'], tf=props['tf'],
            k=props['k'],
        )
    except ImportError:
        return props


def _section_sort_key(name: str) -> Tuple[int, int]:
    """Sort key: by depth descending, then weight descending."""
    parts = name.replace('W', '').split('x')
    try:
        return (-int(parts[0]), -int(parts[1]))
    except (ValueError, IndexError):
        return (0, 0)
